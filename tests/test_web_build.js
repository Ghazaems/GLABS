const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os');
const {build} = require('../web/build-data.cjs');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'glabs-build-test-'));
const write = (name, value) => fs.writeFileSync(path.join(root, name), JSON.stringify(value));
const history = [{date:'2026-10-15',close:105,benchmark:7000}];
const row = {ticker:'AKKU',last_price_date:'2026-10-15',signal:'pantau',score:30,
  price_history:history,volatility:{status:'ok',price_history:history}};
const dashboard = {market_data_date:'2026-10-16',universe_tickers:['AKKU','ABCD'],watchlist:[row],summary:{top_pick:row}};
write('dashboard_data.json',dashboard);
write('purbaya_activity_data.json',{provider:'purbayasadewa.id',method_version:2,market_data_date:'2026-10-16',stocks:{AKKU:{status:'unavailable'},ABCD:{status:'ok',history}}});
const entity = {symbol:'AKKU',history,chart_history:history};
write('sector_rotation_data.json',{modes:{weekly:{stocks:[entity],sectors:[]},daily:{large:'duplicate'}}});
write('rotation_history_data.json',{stocks:[{symbol:'AKKU',prices:history}]});
const before = fs.readFileSync(path.join(root,'dashboard_data.json'),'utf8');
build(root);
const read = name => JSON.parse(fs.readFileSync(path.join(root,name),'utf8'));
const overview=read('dashboard_overview.json'),assets=overview.ui_assets;
assert.deepEqual(overview.universe_tickers,dashboard.universe_tickers);
assert.equal(overview.watchlist[0].signal,'pantau');
assert.equal(overview.watchlist[0].last_price_date,'2026-10-15');
assert.equal(overview.watchlist[0].price_history,undefined);
assert.equal(overview.summary.top_pick.volatility.price_history,undefined);
assert.deepEqual(read(assets.details_base+'AKKU.json').stock,row);
assert.deepEqual(read(assets.activity_base+'ABCD.json').stocks.ABCD.history,history);
assert.equal(Object.keys(read(assets.activity_base+'ABCD.json').stocks).length,1);
assert.equal(read(assets.rotation).modes.daily,undefined);
assert.deepEqual(read(assets.rotation).modes.weekly.stocks[0].packed_history,[['2026-10-15',105,7000]]);
assert.equal(fs.readFileSync(path.join(root,'dashboard_data.json'),'utf8'),before);
build(root);
assert.deepEqual(read('dashboard_overview.json').ui_assets,assets,'content addressed assets deterministic');
console.log('Web build preserves exact universe, full histories, signals and real dates; compact overview deterministic.');
